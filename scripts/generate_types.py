"""Emit normalized-document TypeScript types from the actual Pydantic schema."""
import json
from pathlib import Path

from o3d.model import Project

ROOT = Path(__file__).resolve().parents[1]


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "anyOf" in schema or "oneOf" in schema:
        return " | ".join(ts(v) for v in schema.get("anyOf", schema.get("oneOf")))
    kind = schema.get("type")
    if kind in ("number", "integer"):
        return "number"
    if kind in ("boolean", "string", "null"):
        return kind
    if kind == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(ts(v) for v in schema["prefixItems"]) + "]"
        return f"({ts(schema.get('items', {}))})[]"
    if kind == "object":
        if "patternProperties" in schema:
            return f"Record<string, {ts(next(iter(schema['patternProperties'].values())))}>"
        if "properties" in schema:
            return "{\n" + "\n".join(f"  {json.dumps(k)}: {ts(v)};" for k, v in schema["properties"].items()) + "\n}"
        additional = schema.get("additionalProperties", {})
        return f"Record<string, {ts(additional) if isinstance(additional, dict) else 'unknown'}>"
    return "unknown"


if __name__ == "__main__":
    schema = Project.model_json_schema()
    declarations = ["// Generated by scripts/generate_types.py. Normalized API documents include defaults.\n"]
    for name, definition in schema.get("$defs", {}).items():
        declarations.append(f"export type {name} = {ts(definition)};\n")
    declarations.append(f"export type Project = {ts(schema)};\n")
    (ROOT / "frontend/src/generated.ts").write_text("\n".join(declarations))
    (ROOT / "docs/project.schema.json").write_text(json.dumps(schema, indent=2) + "\n")
