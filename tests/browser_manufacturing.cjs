const setupName='Browser verified milling '+Date.now();await page.getByLabel('Setup name',{exact:true}).fill(setupName);
await page.getByRole('button',{name:'Save process',exact:true}).click();
await page.getByRole('button',{name:'Saved',exact:true}).waitFor();
await page.getByRole('button',{name:'Generate NC & checks',exact:true}).click();
await page.getByText('Ready for process review',{exact:true}).waitFor({timeout:60000});
const link=page.getByRole('link',{name:'program.ngc',exact:true});await link.waitFor();const href=await link.getAttribute('href');
const nc=await (await page.request.get(url+href)).text();
if(!nc.includes('G43 H1')||!nc.includes('T2 M6'))throw Error('Posted program missing tool offsets/tools');
await page.screenshot({path:output+'/milling.png',fullPage:true});
