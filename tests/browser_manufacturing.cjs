await page.getByRole('button',{name:'Machining',exact:true}).click();
await page.getByLabel('Setup name',{exact:true}).fill('Browser changed setup');await page.getByRole('button',{name:'Save process',exact:true}).click();await page.getByRole('button',{name:'Saved',exact:true}).waitFor();
const stale=await page.request.get(url+href);
if(stale.status()!==409)throw Error('Stale NC remained accessible: '+stale.status());
