await page.getByText('1 passed · 1 failed',{exact:true}).waitFor({timeout:60000});
await page.getByRole('button',{name:'Sheet & cutting',exact:true}).click();
await page.getByRole('button',{name:'Nest & export DXF',exact:true}).click();
await page.getByRole('link',{name:'sheet-1.dxf',exact:true}).waitFor({timeout:60000});
